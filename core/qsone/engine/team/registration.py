"""Registers the eight team tools in `engine.tools`, once, when the package is imported."""

from qsone import copy
from qsone.engine.tools import Tool, register

from .handlers import (
    _build_specialist,
    _delegate,
    _make_deliverable,
    _plan_brief,
    _save_desk,
    _send_message,
    _submit_for_check,
    _use_desk,
)
from .schemas import (
    _CHECK_DOC,
    _CHECK_EXAMPLE,
    _DELEGATE_DOC,
    _DELEGATE_EXAMPLE,
    _DELIVERABLE_DOC,
    _DELIVERABLE_EXAMPLE,
    _MESSAGE_DOC,
    _MESSAGE_EXAMPLE,
    _PLAN_DOC,
    _PLAN_EXAMPLE,
    _SAVE_DESK_DOC,
    _SAVE_DESK_EXAMPLE,
    _SPECIALIST_DOC,
    _SPECIALIST_EXAMPLE,
    _USE_DESK_DOC,
    _USE_DESK_EXAMPLE,
    CheckArgs,
    DelegateArgs,
    DeliverableArgs,
    MessageArgs,
    PlanArgs,
    SaveDeskArgs,
    SpecialistArgs,
    UseDeskArgs,
)

# Registration ---------------------------------------------------------------------------------

_LEAD = frozenset({"lead"})
_TEAM = frozenset({"lead", "specialist"})

for _tool in (
    Tool(
        "plan_brief",
        _PLAN_DOC,
        PlanArgs,
        "read",
        _plan_brief,
        lambda a: copy.TOOL_PLAN_BRIEF,
        lead_only=True,
        example=_PLAN_EXAMPLE,
        roles=_LEAD,
        group="team",
    ),
    Tool(
        "build_specialist",
        _SPECIALIST_DOC,
        SpecialistArgs,
        "write",
        _build_specialist,
        lambda a: copy.fill(copy.TOOL_BUILD_SPECIALIST, name={"en": a.name_en, "ar": a.name_ar}),
        lead_only=True,
        writes=True,
        example=_SPECIALIST_EXAMPLE,
        roles=_LEAD,
        group="team",
    ),
    Tool(
        "delegate",
        _DELEGATE_DOC,
        DelegateArgs,
        "write",
        _delegate,
        lambda a: copy.TOOL_DELEGATE,
        deferred=True,
        lead_only=True,
        example=_DELEGATE_EXAMPLE,
        roles=_LEAD,
        group="team",
    ),
    Tool(
        "send_message",
        _MESSAGE_DOC,
        MessageArgs,
        "write",
        _send_message,
        lambda a: copy.TOOL_SEND_MESSAGE,
        writes=True,
        example=_MESSAGE_EXAMPLE,
        roles=_TEAM,
        group="team",
    ),
    Tool(
        "make_deliverable",
        _DELIVERABLE_DOC,
        DeliverableArgs,
        "write",
        _make_deliverable,
        lambda a: copy.fill(copy.TOOL_MAKE_DELIVERABLE, title=a.title),
        writes=True,
        example=_DELIVERABLE_EXAMPLE,
        roles=_TEAM,
        group="team",
    ),
    Tool(
        "submit_for_check",
        _CHECK_DOC,
        CheckArgs,
        "read",
        _submit_for_check,
        lambda a: copy.TOOL_SUBMIT_FOR_CHECK,
        deferred=True,
        lead_only=True,
        example=_CHECK_EXAMPLE,
        roles=_LEAD,
        group="team",
    ),
    Tool(
        "save_desk",
        _SAVE_DESK_DOC,
        SaveDeskArgs,
        "write",
        _save_desk,
        lambda a: copy.fill(copy.TOOL_SAVE_DESK, desk={"en": a.name_en, "ar": a.name_ar}),
        lead_only=True,
        writes=True,
        example=_SAVE_DESK_EXAMPLE,
        roles=_LEAD,
        group="team",
    ),
    Tool(
        "use_desk",
        _USE_DESK_DOC,
        UseDeskArgs,
        "write",
        _use_desk,
        lambda a: copy.TOOL_USE_DESK,
        lead_only=True,
        writes=True,
        example=_USE_DESK_EXAMPLE,
        roles=_LEAD,
        group="team",
    ),
):
    register(_tool)
